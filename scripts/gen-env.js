#!/usr/bin/env node
// Reads environment variables and writes src/pkjs/env-defaults.js.
// Run before `pebble build` to bake defaults into the bundle:
//
//   npm run gen-env
//
// Supported variables:
//   HB_PROVIDER        — active provider: claude | gemini | chatgpt
//   HB_CLAUDE_API_KEY  — Anthropic API key
//   HB_GEMINI_API_KEY  — Google Gemini API key
//   HB_CHATGPT_API_KEY — OpenAI ChatGPT API key
//   HB_MODEL           — model ID (must match the chosen provider)
//   HB_MAX_TOKENS      — max response tokens (integer)
//   HB_MAX_HISTORY     — conversation memory turns (integer, 0 = none)

var fs   = require('fs');
var path = require('path');

var env = process.env;

function strVal(envVar) {
  var v = env[envVar];
  return (v !== undefined && v !== '') ? v : null;
}

function intVal(envVar) {
  var v = parseInt(env[envVar]);
  return isNaN(v) ? null : v;
}

var values = {
  PROVIDER:        strVal('HB_PROVIDER'),
  CLAUDE_API_KEY:  strVal('HB_CLAUDE_API_KEY'),
  GEMINI_API_KEY:  strVal('HB_GEMINI_API_KEY'),
  CHATGPT_API_KEY: strVal('HB_CHATGPT_API_KEY'),
  MODEL:           strVal('HB_MODEL'),
  MAX_TOKENS:      intVal('HB_MAX_TOKENS'),
  MAX_HISTORY:     intVal('HB_MAX_HISTORY')
};

function jsLiteral(v) {
  if (v === null)            return 'null';
  if (typeof v === 'number') return String(v);
  return "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

var set = Object.keys(values).filter(function(k) { return values[k] !== null; });

var lines = [
  '// Auto-generated by scripts/gen-env.js — do not edit by hand.',
  '// Run `npm run gen-env` before `pebble build` to populate from environment variables:',
  '//   HB_PROVIDER, HB_CLAUDE_API_KEY, HB_GEMINI_API_KEY, HB_CHATGPT_API_KEY,',
  '//   HB_MODEL, HB_MAX_TOKENS, HB_MAX_HISTORY',
  '',
  'module.exports = {'
];

var keys = ['PROVIDER', 'CLAUDE_API_KEY', 'GEMINI_API_KEY', 'CHATGPT_API_KEY',
            'MODEL', 'MAX_TOKENS', 'MAX_HISTORY'];
keys.forEach(function(k, i) {
  var val    = values[k] !== null ? values[k] : (k === 'MAX_TOKENS' || k === 'MAX_HISTORY' ? null : '');
  var comma  = i < keys.length - 1 ? ',' : '';
  // Use 0 and -1 as sentinels for "not set" on numeric fields
  if (k === 'MAX_TOKENS'  && val === null) val = 0;
  if (k === 'MAX_HISTORY' && val === null) val = -1;
  lines.push('  ' + k + ': ' + jsLiteral(val) + comma);
});

lines.push('};', '');

var outPath = path.join(__dirname, '..', 'src', 'pkjs', 'env-defaults.js');
fs.writeFileSync(outPath, lines.join('\n'), 'utf8');

if (set.length > 0) {
  console.log('gen-env: wrote ' + set.length + ' value(s) from environment: ' + set.join(', '));
} else {
  console.log('gen-env: no HB_* environment variables set — wrote empty defaults.');
}
