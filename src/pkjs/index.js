// ---- Usage tracking ----

var USAGE_PROVIDERS = ['claude', 'gemini', 'chatgpt'];

function loadUsage() {
  var usage = {};
  USAGE_PROVIDERS.forEach(function(p) {
    usage[p] = {
      requests:  parseInt(localStorage.getItem('usage_' + p + '_requests'))   || 0,
      tokensIn:  parseInt(localStorage.getItem('usage_' + p + '_tokens_in'))  || 0,
      tokensOut: parseInt(localStorage.getItem('usage_' + p + '_tokens_out')) || 0
    };
  });
  return usage;
}

function recordUsage(provider, usage) {
  if (!usage) return;
  var r  = parseInt(localStorage.getItem('usage_' + provider + '_requests'))   || 0;
  var ti = parseInt(localStorage.getItem('usage_' + provider + '_tokens_in'))  || 0;
  var to = parseInt(localStorage.getItem('usage_' + provider + '_tokens_out')) || 0;
  localStorage.setItem('usage_' + provider + '_requests',   r  + 1);
  localStorage.setItem('usage_' + provider + '_tokens_in',  ti + (usage.inputTokens  || 0));
  localStorage.setItem('usage_' + provider + '_tokens_out', to + (usage.outputTokens || 0));
}

function resetUsageStats() {
  USAGE_PROVIDERS.forEach(function(p) {
    localStorage.removeItem('usage_' + p + '_requests');
    localStorage.removeItem('usage_' + p + '_tokens_in');
    localStorage.removeItem('usage_' + p + '_tokens_out');
  });
}

// ---- Utility ----

function truncateForWatch(text, maxChars) {
  maxChars = maxChars || 1800;
  if (text.length <= maxChars) return text;
  return text.substring(0, maxChars - 3) + '...';
}

function sendToWatch(key, value) {
  var msg = {};
  msg[key] = value;
  var attempts = 0;
  function trySend() {
    attempts++;
    Pebble.sendAppMessage(
      msg,
      function() { console.log('Message sent OK (attempt ' + attempts + ')'); },
      function(e) {
        console.log('Send failed (attempt ' + attempts + '): ' + JSON.stringify(e));
        if (attempts < 4) {
          setTimeout(trySend, 500 * attempts);
        }
      }
    );
  }
  trySend();
}

function sendToWatchMulti(dict) {
  var attempts = 0;
  function trySend() {
    attempts++;
    Pebble.sendAppMessage(
      dict,
      function() { console.log('Multi-msg sent OK (attempt ' + attempts + ')'); },
      function(e) {
        console.log('Multi-msg failed (attempt ' + attempts + '): ' + JSON.stringify(e));
        if (attempts < 4) setTimeout(trySend, 500 * attempts);
      }
    );
  }
  trySend();
}

// Send the next upcoming alarm's timestamp + label to the watch so it can
// schedule a wakeup. Only runs when alarmVibrate is enabled in settings.
function armNextAlarmWakeup() {
  var settings = loadSettings();
  if (!settings.alarmVibrate) return;

  var list = [];
  try { list = JSON.parse(localStorage.getItem('mabel_alarms') || '[]'); } catch (e) {}

  var now    = Date.now();
  var future = list.filter(function(a) { return new Date(a.when).getTime() > now; });
  if (future.length === 0) return;

  future.sort(function(a, b) { return a.when < b.when ? -1 : 1; });
  var next = future[0];
  var ts   = Math.floor(new Date(next.when).getTime() / 1000);
  var label = (next.what || 'Alarm').substring(0, 63);

  var dict = {};
  dict[KEY_ALARM_WAKEUP] = ts;
  dict[KEY_ALARM_LABEL]  = label;
  sendToWatchMulti(dict);
  console.log('Armed alarm wakeup: "' + label + '" at ' + next.when);
}

// ---- Reminder / Timeline pin helpers ----

function padTwo(n) { return (n < 10 ? '0' : '') + n; }

// Build the addendum injected into the system prompt so the AI knows the
// current local time and how to signal a reminder back to us.
function buildReminderAddendum() {
  var now       = new Date();
  var offMin    = -now.getTimezoneOffset();
  var offSign   = offMin >= 0 ? '+' : '-';
  var absMin    = Math.abs(offMin);
  var offStr    = offSign + padTwo(Math.floor(absMin / 60)) + ':' + padTwo(absMin % 60);
  var localISO  =
    now.getFullYear()           + '-' +
    padTwo(now.getMonth() + 1)  + '-' +
    padTwo(now.getDate())       + 'T' +
    padTwo(now.getHours())      + ':' +
    padTwo(now.getMinutes())    + ':00' +
    offStr;

  return (
    'Current local date/time: ' + localISO + '\n' +
    'When the user requests a reminder, place this block at the very start of your response:\n' +
    '[REMINDER]{"what":"brief label","when":"YYYY-MM-DDTHH:MM:SS' + offStr + '"}[/REMINDER]\n' +
    'When the user requests a timer, place this block at the very start of your response:\n' +
    '[TIMER]{"what":"brief label","when":"YYYY-MM-DDTHH:MM:SS' + offStr + '"}[/TIMER]\n' +
    'When the user requests an alarm, place this block at the very start of your response:\n' +
    '[ALARM]{"what":"brief label","when":"YYYY-MM-DDTHH:MM:SS' + offStr + '"}[/ALARM]\n' +
    'Always use local date/time with the ' + offStr + ' offset shown above — never convert to UTC. ' +
    'For timers, add the requested duration to the current local time above. ' +
    'After the block, give a brief plain-text confirmation only — no markdown.'
  );
}

// Extract the first [REMINDER]{...}[/REMINDER] block from the AI reply.
function parseReminderBlock(text) {
  var match = text.match(/\[REMINDER\]([\s\S]*?)\[\/REMINDER\]/);
  if (!match) return null;
  try { return JSON.parse(match[1].trim()); } catch (e) { return null; }
}

// Return the reply with any [REMINDER]...[/REMINDER] blocks removed.
function stripReminderBlock(text) {
  return text.replace(/\[REMINDER\][\s\S]*?\[\/REMINDER\]\s*/g, '').trim();
}

function parseTimerBlock(text) {
  var match = text.match(/\[TIMER\]([\s\S]*?)\[\/TIMER\]/);
  if (!match) return null;
  try { return JSON.parse(match[1].trim()); } catch (e) { return null; }
}

function stripTimerBlock(text) {
  return text.replace(/\[TIMER\][\s\S]*?\[\/TIMER\]\s*/g, '').trim();
}

function parseAlarmBlock(text) {
  var match = text.match(/\[ALARM\]([\s\S]*?)\[\/ALARM\]/);
  if (!match) return null;
  try { return JSON.parse(match[1].trim()); } catch (e) { return null; }
}

function stripAlarmBlock(text) {
  return text.replace(/\[ALARM\][\s\S]*?\[\/ALARM\]\s*/g, '').trim();
}

