function loadSettings() {
  var maxTokens  = parseInt(localStorage.getItem('maxTokens'));
  var maxHistory = parseInt(localStorage.getItem('maxHistory'));
  // Migrate legacy single apiKey to claudeApiKey
  var legacyKey  = localStorage.getItem('apiKey');
  return {
    provider:      localStorage.getItem('provider')      || DEFAULT_SETTINGS.provider,
    claudeApiKey:  localStorage.getItem('claudeApiKey')  || legacyKey || DEFAULT_SETTINGS.claudeApiKey,
    geminiApiKey:  localStorage.getItem('geminiApiKey')  || DEFAULT_SETTINGS.geminiApiKey,
    chatgptApiKey: localStorage.getItem('chatgptApiKey') || DEFAULT_SETTINGS.chatgptApiKey,
    model:         localStorage.getItem('model')         || DEFAULT_SETTINGS.model,
    maxTokens:     isNaN(maxTokens)  ? DEFAULT_SETTINGS.maxTokens  : maxTokens,
    maxHistory:    isNaN(maxHistory) ? DEFAULT_SETTINGS.maxHistory : maxHistory,
    alarmVibrate:  localStorage.getItem('alarmVibrate') === 'true'
  };
}

