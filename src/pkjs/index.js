// Map WMO weather codes to short descriptions.
function wmoDescription(code) {
  if (code === 0)  return 'Clear';
  if (code === 1)  return 'Mainly clear';
  if (code === 2)  return 'Partly cloudy';
  if (code === 3)  return 'Overcast';
  if (code <= 48)  return 'Foggy';
  if (code <= 57)  return 'Drizzle';
  if (code <= 67)  return 'Rain';
  if (code <= 77)  return 'Snow';
  if (code <= 82)  return 'Showers';
  if (code <= 86)  return 'Snow showers';
  if (code <= 99)  return 'Thunderstorm';
  return 'Unknown';
}

// Convert wind degrees to compass direction.
function degreesToCompass(deg) {
  var dirs = ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW'];
  return dirs[Math.round(deg / 45) % 8];
}

// Returns true for IANA timezones where Fahrenheit is the standard unit.
// Prefix matching covers sub-zones (e.g. America/Indiana/Indianapolis).
function useFahrenheitForTimezone(tz) {
  var zones = [
    'America/New_York', 'America/Chicago', 'America/Denver', 'America/Los_Angeles',
    'America/Phoenix', 'America/Anchorage', 'America/Adak', 'America/Detroit',
    'America/Boise', 'America/Juneau', 'America/Sitka', 'America/Metlakatla',
    'America/Yakutat', 'America/Nome', 'America/Menominee',
    'America/Indiana', 'America/Kentucky', 'America/North_Dakota',
    'Pacific/Honolulu', 'America/Puerto_Rico', 'Pacific/Guam', 'Pacific/Saipan',
    'Pacific/Pago_Pago', 'America/Nassau', 'America/Cayman', 'America/Belize',
    'Africa/Monrovia', 'Pacific/Palau', 'Pacific/Majuro', 'Pacific/Pohnpei',
    'Pacific/Chuuk', 'Pacific/Kosrae'
  ];
  for (var i = 0; i < zones.length; i++) {
    if (tz.indexOf(zones[i]) === 0) return true;
  }
  return false;
}

function fetchWeather() {
  navigator.geolocation.getCurrentPosition(
    function(pos) {
      var lat = pos.coords.latitude.toFixed(4);
      var lon = pos.coords.longitude.toFixed(4);
      var tz  = Intl.DateTimeFormat().resolvedOptions().timeZone || '';
      var useFahrenheit = useFahrenheitForTimezone(tz);
      var tempUnit = useFahrenheit ? 'fahrenheit' : 'celsius';
      var tempSym  = useFahrenheit ? 'F' : 'C';
      var url =
        'https://api.open-meteo.com/v1/forecast' +
        '?latitude=' + lat + '&longitude=' + lon +
        '&current=temperature_2m,apparent_temperature,relative_humidity_2m,' +
        'wind_speed_10m,wind_direction_10m,weather_code' +
        '&hourly=temperature_2m,weather_code' +
        '&temperature_unit=' + tempUnit +
        '&wind_speed_unit=mph' +
        '&timezone=auto' +
        '&forecast_days=1';

      var xhr = new XMLHttpRequest();
      xhr.open('GET', url, true);
      xhr.onreadystatechange = function() {
        if (xhr.readyState !== 4) return;
        if (xhr.status !== 200) {
          sendToWatch(KEY_WEATHER_DATA, 'Weather unavailable.');
          return;
        }
        try {
          var data = JSON.parse(xhr.responseText);
          var c    = data.current;
          var temp  = Math.round(c.temperature_2m);
          var feels = Math.round(c.apparent_temperature);
          var humid = Math.round(c.relative_humidity_2m);
          var wind  = Math.round(c.wind_speed_10m);
          var wdir  = degreesToCompass(c.wind_direction_10m);
          var desc  = wmoDescription(c.weather_code);

          // Find the next hour's slot in the hourly forecast.
          var hourlyTimes = data.hourly.time;
          var hourlyTemps = data.hourly.temperature_2m;
          var hourlyCodes = data.hourly.weather_code;
          var nextHour = (new Date().getHours() + 1) % 24;
          var nextIdx = -1;
          for (var i = 0; i < hourlyTimes.length; i++) {
            var h = parseInt(hourlyTimes[i].split('T')[1].split(':')[0], 10);
            if (h === nextHour) { nextIdx = i; break; }
          }

          var text =
            temp + '\xB0' + tempSym + ' ' + desc + '\n' +
            'Feels: ' + feels + '\xB0' + tempSym + '\n' +
            'Wind: ' + wind + ' mph ' + wdir + '\n' +
            'Humidity: ' + humid + '%';
          if (nextIdx >= 0) {
            var ntemp = Math.round(hourlyTemps[nextIdx]);
            var ndesc = wmoDescription(hourlyCodes[nextIdx]);
            text += '\n\n+1hr: ' + ntemp + '\xB0' + tempSym + ' ' + ndesc;
          }
          sendToWatch(KEY_WEATHER_DATA, truncateForWatch(text, 500));
        } catch (e) {
          console.log('Weather parse error: ' + e);
          sendToWatch(KEY_WEATHER_DATA, 'Weather parse error.');
        }
      };
      xhr.onerror = function() {
        sendToWatch(KEY_WEATHER_DATA, 'Weather network error.');
      };
      xhr.send();
    },
    function(err) {
      console.log('Geolocation error: ' + err.message);
      sendToWatch(KEY_WEATHER_DATA, 'Location unavailable.');
    },
    { timeout: 10000 }
  );
}

