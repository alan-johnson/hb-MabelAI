function saveItem(storageKey, what, when) {
  var list = [];
  try { list = JSON.parse(localStorage.getItem(storageKey) || '[]'); } catch (e) {}
  list.push({ what: what, when: when });
  localStorage.setItem(storageKey, JSON.stringify(list));
}

function saveReminder(what, when) { saveItem('mabel_reminders', what, when); }
function saveTimer(what, when)    { saveItem('mabel_timers',    what, when); }
function saveAlarm(what, when)    { saveItem('mabel_alarms',    what, when); }

function formatItemsForWatch(storageKey, emptyMsg) {
  var list = [];
  try { list = JSON.parse(localStorage.getItem(storageKey) || '[]'); } catch (e) {}
  if (list.length === 0) return emptyMsg;
  list.sort(function(a, b) { return a.when < b.when ? -1 : a.when > b.when ? 1 : 0; });
  var lines = list.map(function(r) {
    var d = new Date(r.when);
    var month  = d.getMonth() + 1;
    var day    = d.getDate();
    var hour   = d.getHours();
    var min    = padTwo(d.getMinutes());
    var ampm   = hour < 12 ? 'AM' : 'PM';
    var hour12 = hour % 12 || 12;
    return r.what + '\n' + month + '/' + day + ' ' + hour12 + ':' + min + ' ' + ampm;
  });
  return truncateForWatch(lines.join('\n\n'), 1800);
}

function formatRemindersForWatch() {
  return formatItemsForWatch('mabel_reminders', 'No reminders yet.\n\nAsk Mabel to set one!');
}

function formatTimersForWatch() {
  return formatItemsForWatch('mabel_timers', 'No timers yet.\n\nAsk Mabel to set one!');
}

function purgePastAlarms() {
  var list = [];
  try { list = JSON.parse(localStorage.getItem('mabel_alarms') || '[]'); } catch (e) {}
  var now    = Date.now();
  var future = list.filter(function(a) { return new Date(a.when).getTime() > now; });
  if (future.length !== list.length) {
    localStorage.setItem('mabel_alarms', JSON.stringify(future));
  }
}

function formatAlarmsForWatch() {
  purgePastAlarms();
  return formatItemsForWatch('mabel_alarms', 'No alarms yet.\n\nAsk Mabel to set one!');
}

function formatTokensForWatch() {
  var usage    = loadUsage();
  var settings = loadSettings();
  var maxTok   = settings.maxTokens;
  var lines    = [];

  USAGE_PROVIDERS.forEach(function(p) {
    var u    = usage[p];
    var name = PROVIDER_NAMES[p] || p;
    lines.push(name + ': ' + u.requests + ' req');
    lines.push('In: ' + u.tokensIn + ' Out: ' + u.tokensOut);
    lines.push('Limit: ' + maxTok + '/req');
    lines.push('');
  });

  var reminders = 0, timers = 0, alarms = 0;
  try { reminders = JSON.parse(localStorage.getItem('mabel_reminders') || '[]').length; } catch (e) {}
  try { timers    = JSON.parse(localStorage.getItem('mabel_timers')    || '[]').length; } catch (e) {}
  try { alarms    = JSON.parse(localStorage.getItem('mabel_alarms')    || '[]').length; } catch (e) {}

  lines.push('Rebble:');
  lines.push('Reminders: ' + reminders);
  lines.push('Timers: ' + timers);
  lines.push('Alarms: ' + alarms);

  return truncateForWatch(lines.join('\n'), 500);
}

// Generate a unique pin ID.
function makePinId() {
  return 'hb-' + Date.now().toString(16) +
         '-'   + Math.floor(Math.random() * 0xFFFFFF).toString(16);
}

// Create a Rebble timeline pin with a notification.
// icon: a system://images/ identifier string.
// Calls onDone(errorString|null) when complete.
function createTimelinePin(what, when, icon, onDone) {
  Pebble.getTimelineToken(
    function(token) {
      var pinId = makePinId();
      var pin = {
        id:       pinId,
        time:     when,
        duration: 5,
        layout: {
          type:     'genericPin',
          title:    what,
          tinyIcon: icon
        },
        reminders: [{
          time:   when,
          layout: { type: 'genericReminder', title: what }
        }]
      };

      var xhr = new XMLHttpRequest();
      xhr.open('PUT', 'https://timeline-api.rebble.io/v1/user/pins/' + pinId, true);
      xhr.setRequestHeader('Content-Type', 'application/json');
      xhr.setRequestHeader('X-User-Token',  token);
      var finished = false;
      xhr.onreadystatechange = function() {
        if (xhr.readyState !== 4 || finished) return;
        finished = true;
        if (xhr.status >= 200 && xhr.status < 300) {
          console.log('Timeline pin created: ' + pinId);
          onDone(null);
        } else {
          console.log('Timeline pin error ' + xhr.status + ': ' + xhr.responseText);
          onDone('pin error ' + xhr.status);
        }
      };
      xhr.onerror = function() {
        if (finished) return;
        finished = true;
        onDone('pin network error');
      };
      xhr.send(JSON.stringify(pin));
    },
    function(err) {
      console.log('getTimelineToken failed: ' + err);
      onDone('timeline token error');
    }
  );
}

