Pebble.addEventListener('webviewclosed', function(e) {
  if (!e.response) return;
  try {
    var settings     = JSON.parse(decodeURIComponent(e.response));
    if (settings.resetUsage) { resetUsageStats(); }
    saveSettings(settings);
    console.log('Settings saved: ' + JSON.stringify(settings));
    armNextAlarmWakeup();
    var name = PROVIDER_NAMES[settings.provider] || 'AI';
    sendToWatch(KEY_STATUS, 'Settings saved! Press MIC to ask ' + name + '.');
  } catch (err) {
    console.log('Failed to parse config response: ' + err);
  }
});

Pebble.addEventListener('appmessage', function(e) {
  var payload = e.payload;
  console.log('Received from watch: ' + JSON.stringify(payload));
  if (payload[KEY_QUERY] !== undefined) {
    var query = payload[KEY_QUERY];
    // Small delay so the AppMessage ACK handshake completes before we
    // try to send a new message back to the watch.
    setTimeout(function() { askAI(query); }, 100);
  }
  if (payload[KEY_REMINDERS_REQUEST] !== undefined) {
    setTimeout(function() {
      sendToWatch(KEY_REMINDERS_LIST, formatRemindersForWatch());
    }, 100);
  }
  if (payload[KEY_TIMERS_REQUEST] !== undefined) {
    setTimeout(function() {
      sendToWatch(KEY_TIMERS_LIST, formatTimersForWatch());
    }, 100);
  }
  if (payload[KEY_ALARMS_REQUEST] !== undefined) {
    setTimeout(function() {
      sendToWatch(KEY_ALARMS_LIST, formatAlarmsForWatch());
    }, 100);
  }
  if (payload[KEY_WEATHER_REQUEST] !== undefined) {
    setTimeout(function() { fetchWeather(); }, 100);
  }
  if (payload[KEY_TOKENS_REQUEST] !== undefined) {
    setTimeout(function() {
      sendToWatch(KEY_TOKENS_DATA, formatTokensForWatch());
    }, 100);
  }
  if (payload[KEY_ALARM_DISMISSED] !== undefined) {
    // Remove the alarm that just fired (the earliest past-due one).
    var list = [];
    try { list = JSON.parse(localStorage.getItem('mabel_alarms') || '[]'); } catch (e) {}
    var now  = Date.now();
    var past = list.filter(function(a) { return new Date(a.when).getTime() <= now; });
    var future = list.filter(function(a) { return new Date(a.when).getTime() > now; });
    past.sort(function(a, b) { return a.when < b.when ? 1 : -1; });
    if (past.length > 0) past.shift();  // drop the most recently fired entry
    localStorage.setItem('mabel_alarms', JSON.stringify(past.concat(future)));
    setTimeout(armNextAlarmWakeup, 100);
  }
});
