// PebbleKit JS — runs on the phone, bridges Pebble <-> AI provider

var configPage   = require('./config');
var aiProviders  = require('./ai-providers');
var envDefaults  = require('./env-defaults');

// Message key constants — Core Devices Pebble app exposes messageKeys by
// string name in JS (e.g. "KEY_QUERY"), not by integer value (0).
var KEY_QUERY             = 'KEY_QUERY';
var KEY_RESPONSE          = 'KEY_RESPONSE';
var KEY_STATUS            = 'KEY_STATUS';
var KEY_REMINDERS_REQUEST = 'KEY_REMINDERS_REQUEST';
var KEY_REMINDERS_LIST    = 'KEY_REMINDERS_LIST';

// ---- Settings ----
// Values come from env-defaults.js (generated by `npm run gen-env` from HB_* env vars),
// falling back to hard-coded defaults for anything not set.

var DEFAULT_SETTINGS = {
  provider:      envDefaults.PROVIDER        || 'claude',
  claudeApiKey:  envDefaults.CLAUDE_API_KEY  || '',
  geminiApiKey:  envDefaults.GEMINI_API_KEY  || '',
  chatgptApiKey: envDefaults.CHATGPT_API_KEY || '',
  model:         envDefaults.MODEL           || 'claude-haiku-4-5-20251001',
  maxTokens:     envDefaults.MAX_TOKENS  > 0   ? envDefaults.MAX_TOKENS  : 300,
  maxHistory:    envDefaults.MAX_HISTORY >= 0   ? envDefaults.MAX_HISTORY : 4
};

var PROVIDER_NAMES = { claude: 'Claude', gemini: 'Gemini', chatgpt: 'ChatGPT' };

function loadSettings() {
  var maxTokens  = parseInt(localStorage.getItem('maxTokens'));
  var maxHistory = parseInt(localStorage.getItem('maxHistory'));
  // Migrate legacy single apiKey to claudeApiKey
  var legacyKey  = localStorage.getItem('apiKey');
  return {
    provider:      localStorage.getItem('provider')      || DEFAULT_SETTINGS.provider,
    claudeApiKey:  localStorage.getItem('claudeApiKey')  || legacyKey || DEFAULT_SETTINGS.claudeApiKey,
    geminiApiKey:  localStorage.getItem('geminiApiKey')  || DEFAULT_SETTINGS.geminiApiKey,
    chatgptApiKey: localStorage.getItem('chatgptApiKey') || DEFAULT_SETTINGS.chatgptApiKey,
    model:         localStorage.getItem('model')         || DEFAULT_SETTINGS.model,
    maxTokens:     isNaN(maxTokens)  ? DEFAULT_SETTINGS.maxTokens  : maxTokens,
    maxHistory:    isNaN(maxHistory) ? DEFAULT_SETTINGS.maxHistory : maxHistory
  };
}

function saveSettings(settings) {
  localStorage.setItem('provider',      settings.provider);
  localStorage.setItem('claudeApiKey',  settings.claudeApiKey);
  localStorage.setItem('geminiApiKey',  settings.geminiApiKey);
  localStorage.setItem('chatgptApiKey', settings.chatgptApiKey);
  localStorage.setItem('model',         settings.model);
  localStorage.setItem('maxTokens',     settings.maxTokens);
  localStorage.setItem('maxHistory',    settings.maxHistory);
}

// ---- Usage tracking ----

var USAGE_PROVIDERS = ['claude', 'gemini', 'chatgpt'];

function loadUsage() {
  var usage = {};
  USAGE_PROVIDERS.forEach(function(p) {
    usage[p] = {
      requests:  parseInt(localStorage.getItem('usage_' + p + '_requests'))   || 0,
      tokensIn:  parseInt(localStorage.getItem('usage_' + p + '_tokens_in'))  || 0,
      tokensOut: parseInt(localStorage.getItem('usage_' + p + '_tokens_out')) || 0
    };
  });
  return usage;
}

function recordUsage(provider, usage) {
  if (!usage) return;
  var r  = parseInt(localStorage.getItem('usage_' + provider + '_requests'))   || 0;
  var ti = parseInt(localStorage.getItem('usage_' + provider + '_tokens_in'))  || 0;
  var to = parseInt(localStorage.getItem('usage_' + provider + '_tokens_out')) || 0;
  localStorage.setItem('usage_' + provider + '_requests',   r  + 1);
  localStorage.setItem('usage_' + provider + '_tokens_in',  ti + (usage.inputTokens  || 0));
  localStorage.setItem('usage_' + provider + '_tokens_out', to + (usage.outputTokens || 0));
}

function resetUsageStats() {
  USAGE_PROVIDERS.forEach(function(p) {
    localStorage.removeItem('usage_' + p + '_requests');
    localStorage.removeItem('usage_' + p + '_tokens_in');
    localStorage.removeItem('usage_' + p + '_tokens_out');
  });
}

// ---- Utility ----

function truncateForWatch(text, maxChars) {
  maxChars = maxChars || 1800;
  if (text.length <= maxChars) return text;
  return text.substring(0, maxChars - 3) + '...';
}

function sendToWatch(key, value) {
  var msg = {};
  msg[key] = value;
  var attempts = 0;
  function trySend() {
    attempts++;
    Pebble.sendAppMessage(
      msg,
      function() { console.log('Message sent OK (attempt ' + attempts + ')'); },
      function(e) {
        console.log('Send failed (attempt ' + attempts + '): ' + JSON.stringify(e));
        if (attempts < 4) {
          setTimeout(trySend, 500 * attempts);
        }
      }
    );
  }
  trySend();
}

// ---- Reminder / Timeline pin helpers ----

function padTwo(n) { return (n < 10 ? '0' : '') + n; }

// Build the addendum injected into the system prompt so the AI knows the
// current local time and how to signal a reminder back to us.
function buildReminderAddendum() {
  var now       = new Date();
  var offMin    = -now.getTimezoneOffset();
  var offSign   = offMin >= 0 ? '+' : '-';
  var absMin    = Math.abs(offMin);
  var localISO  =
    now.getFullYear()           + '-' +
    padTwo(now.getMonth() + 1)  + '-' +
    padTwo(now.getDate())       + 'T' +
    padTwo(now.getHours())      + ':' +
    padTwo(now.getMinutes())    + ':00' +
    offSign + padTwo(Math.floor(absMin / 60)) + ':' + padTwo(absMin % 60);

  return (
    'Current local date/time (with UTC offset): ' + localISO + '\n' +
    'When the user requests a reminder, alarm, or timer, place this block at the ' +
    'very start of your response (no leading text before it):\n' +
    '[REMINDER]{"what":"brief label","when":"YYYY-MM-DDTHH:MM:SSZ"}[/REMINDER]\n' +
    'Use UTC for the "when" field. After the block, give a brief plain-text ' +
    'confirmation only — no markdown.'
  );
}

// Extract the first [REMINDER]{...}[/REMINDER] block from the AI reply.
function parseReminderBlock(text) {
  var match = text.match(/\[REMINDER\]([\s\S]*?)\[\/REMINDER\]/);
  if (!match) return null;
  try { return JSON.parse(match[1].trim()); } catch (e) { return null; }
}

// Return the reply with any [REMINDER]...[/REMINDER] blocks removed.
function stripReminderBlock(text) {
  return text.replace(/\[REMINDER\][\s\S]*?\[\/REMINDER\]\s*/g, '').trim();
}

// ---- Saved reminders (localStorage) ----

function saveReminder(what, when) {
  var list = [];
  try { list = JSON.parse(localStorage.getItem('mabel_reminders') || '[]'); } catch (e) {}
  list.push({ what: what, when: when });
  localStorage.setItem('mabel_reminders', JSON.stringify(list));
}

function formatRemindersForWatch() {
  var list = [];
  try { list = JSON.parse(localStorage.getItem('mabel_reminders') || '[]'); } catch (e) {}
  if (list.length === 0) {
    return 'No reminders yet.\n\nAsk Mabel to set one!';
  }
  list.sort(function(a, b) { return a.when < b.when ? -1 : a.when > b.when ? 1 : 0; });
  var lines = list.map(function(r) {
    var d = new Date(r.when);
    var month = d.getMonth() + 1;
    var day   = d.getDate();
    var hour  = d.getHours();
    var min   = padTwo(d.getMinutes());
    var ampm  = hour < 12 ? 'AM' : 'PM';
    var hour12 = hour % 12 || 12;
    return r.what + '\n' + month + '/' + day + ' ' + hour12 + ':' + min + ' ' + ampm;
  });
  return truncateForWatch(lines.join('\n\n'), 1800);
}

// Generate a unique pin ID.
function makePinId() {
  return 'hb-' + Date.now().toString(16) +
         '-'   + Math.floor(Math.random() * 0xFFFFFF).toString(16);
}

// Create a Rebble timeline pin with a reminder notification.
// Calls onDone(errorString|null) when complete.
function createTimelinePin(what, when, onDone) {
  Pebble.getTimelineToken(
    function(token) {
      var pinId = makePinId();
      var pin = {
        id:       pinId,
        time:     when,
        duration: 5,
        layout: {
          type:     'genericPin',
          title:    what,
          tinyIcon: 'system://images/ALARM_CLOCK'
        },
        reminders: [{
          time:   when,
          layout: { type: 'genericReminder', title: what }
        }]
      };

      var xhr = new XMLHttpRequest();
      xhr.open('PUT', 'https://timeline-api.rebble.io/v1/user/pins/' + pinId, true);
      xhr.setRequestHeader('Content-Type', 'application/json');
      xhr.setRequestHeader('X-User-Token',  token);
      var finished = false;
      xhr.onreadystatechange = function() {
        if (xhr.readyState !== 4 || finished) return;
        finished = true;
        if (xhr.status >= 200 && xhr.status < 300) {
          console.log('Timeline pin created: ' + pinId);
          saveReminder(what, when);
          onDone(null);
        } else {
          console.log('Timeline pin error ' + xhr.status + ': ' + xhr.responseText);
          onDone('pin error ' + xhr.status);
        }
      };
      xhr.onerror = function() {
        if (finished) return;
        finished = true;
        onDone('pin network error');
      };
      xhr.send(JSON.stringify(pin));
    },
    function(err) {
      console.log('getTimelineToken failed: ' + err);
      onDone('timeline token error');
    }
  );
}

// ---- AI dispatch ----

var conversationHistory = [];
var isLoading = false;

function askAI(userQuery) {
  if (isLoading) {
    console.log('askAI: request already in flight, ignoring duplicate');
    return;
  }

  var settings  = loadSettings();
  var provider  = settings.provider || 'claude';
  var apiKeyMap = {
    claude:  settings.claudeApiKey,
    gemini:  settings.geminiApiKey,
    chatgpt: settings.chatgptApiKey
  };
  var apiKey = apiKeyMap[provider];

  if (!apiKey) {
    sendToWatch(KEY_STATUS, 'No API key. Open settings.');
    return;
  }

  isLoading = true;
  console.log('askAI: provider=' + provider + ' key=' + apiKey.substring(0, 8) + '...');
  sendToWatch(KEY_STATUS, 'Mabel is thinking...');

  if (settings.maxHistory > 0) {
    conversationHistory.push({ role: 'user', content: userQuery });
    while (conversationHistory.length > settings.maxHistory * 2) {
      conversationHistory.shift();
    }
  }

  var providerSettings = {
    apiKey:          apiKey,
    model:           settings.model,
    maxTokens:       settings.maxTokens,
    maxHistory:      settings.maxHistory,
    systemAddendum:  buildReminderAddendum()
  };

  aiProviders.ask(
    provider,
    userQuery,
    conversationHistory,
    providerSettings,
    function(reply, usage) {
      isLoading = false;
      recordUsage(provider, usage);

      var reminder    = parseReminderBlock(reply);
      var displayText = reminder ? stripReminderBlock(reply) : reply;

      if (settings.maxHistory > 0) {
        conversationHistory.push({ role: 'assistant', content: displayText });
      }

      if (reminder && reminder.what && reminder.when) {
        createTimelinePin(reminder.what, reminder.when, function(err) {
          if (err) { console.log('Timeline pin failed: ' + err); }
          sendToWatch(KEY_RESPONSE, truncateForWatch(displayText));
        });
      } else {
        sendToWatch(KEY_RESPONSE, truncateForWatch(displayText));
      }
    },
    function(errMsg) {
      isLoading = false;
      sendToWatch(KEY_STATUS, errMsg);
    }
  );
}

// ---- PebbleKit JS Events ----

Pebble.addEventListener('ready', function() {
  console.log('PebbleKit JS ready');
  var settings = loadSettings();
  var apiKeyMap = {
    claude:  settings.claudeApiKey,
    gemini:  settings.geminiApiKey,
    chatgpt: settings.chatgptApiKey
  };
  // Test query — uncomment only for one-off debugging; leave off to avoid burning API quota.
  // askAI('What is the capital of France?');
  if (!apiKeyMap[settings.provider]) {
    sendToWatch(KEY_STATUS, 'No API key. Open settings.');
  }
});

Pebble.addEventListener('showConfiguration', function() {
  Pebble.openURL(configPage.getConfigPageUrl(loadSettings(), loadUsage()));
});

Pebble.addEventListener('webviewclosed', function(e) {
  if (!e.response) return;
  try {
    var settings     = JSON.parse(decodeURIComponent(e.response));
    if (settings.resetUsage) { resetUsageStats(); }
    saveSettings(settings);
    console.log('Settings saved: ' + JSON.stringify(settings));
    var name = PROVIDER_NAMES[settings.provider] || 'AI';
    sendToWatch(KEY_STATUS, 'Settings saved! Press MIC to ask ' + name + '.');
  } catch (err) {
    console.log('Failed to parse config response: ' + err);
  }
});

Pebble.addEventListener('appmessage', function(e) {
  var payload = e.payload;
  console.log('Received from watch: ' + JSON.stringify(payload));
  if (payload[KEY_QUERY] !== undefined) {
    var query = payload[KEY_QUERY];
    // Small delay so the AppMessage ACK handshake completes before we
    // try to send a new message back to the watch.
    setTimeout(function() { askAI(query); }, 100);
  }
  if (payload[KEY_REMINDERS_REQUEST] !== undefined) {
    setTimeout(function() {
      sendToWatch(KEY_REMINDERS_LIST, formatRemindersForWatch());
    }, 100);
  }
});
