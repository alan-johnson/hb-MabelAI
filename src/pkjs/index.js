var conversationHistory = [];
var isLoading = false;

function askAI(userQuery) {
  if (isLoading) {
    console.log('askAI: request already in flight, ignoring duplicate');
    return;
  }

  var settings  = loadSettings();
  var provider  = settings.provider || 'claude';
  var apiKeyMap = {
    claude:  settings.claudeApiKey,
    gemini:  settings.geminiApiKey,
    chatgpt: settings.chatgptApiKey
  };
  var apiKey = apiKeyMap[provider];

  if (!apiKey) {
    sendToWatch(KEY_STATUS, 'No API key. Open settings.');
    return;
  }

  isLoading = true;
  console.log('askAI: provider=' + provider + ' key=' + apiKey.substring(0, 8) + '...');
  sendToWatch(KEY_STATUS, 'Mabel is thinking...');

  if (settings.maxHistory > 0) {
    conversationHistory.push({ role: 'user', content: userQuery });
    while (conversationHistory.length > settings.maxHistory * 2) {
      conversationHistory.shift();
    }
  }

  var providerSettings = {
    apiKey:          apiKey,
    model:           settings.model,
    maxTokens:       settings.maxTokens,
    maxHistory:      settings.maxHistory,
    systemAddendum:  buildReminderAddendum()
  };

  aiProviders.ask(
    provider,
    userQuery,
    conversationHistory,
    providerSettings,
    function(reply, usage) {
      isLoading = false;
      recordUsage(provider, usage);

      var reminder    = parseReminderBlock(reply);
      var timer       = !reminder ? parseTimerBlock(reply)   : null;
      var alarm       = !reminder && !timer ? parseAlarmBlock(reply) : null;
      var displayText = reply;
      if (reminder) displayText = stripReminderBlock(displayText);
      if (timer)    displayText = stripTimerBlock(displayText);
      if (alarm)    displayText = stripAlarmBlock(displayText);

      if (settings.maxHistory > 0) {
        conversationHistory.push({ role: 'assistant', content: displayText });
      }

      if (reminder && reminder.what && reminder.when) {
        saveReminder(reminder.what, reminder.when);
        createTimelinePin(reminder.what, reminder.when, 'system://images/ALARM_CLOCK', function(err) {
          if (err) { console.log('Timeline pin failed: ' + err); }
          sendToWatch(KEY_RESPONSE, truncateForWatch(displayText));
        });
      } else if (timer && timer.what && timer.when) {
        saveTimer(timer.what, timer.when);
        createTimelinePin(timer.what, timer.when, 'system://images/GENERIC_REMINDER', function(err) {
          if (err) { console.log('Timeline pin failed: ' + err); }
          sendToWatch(KEY_RESPONSE, truncateForWatch(displayText));
        });
      } else if (alarm && alarm.what && alarm.when) {
        saveAlarm(alarm.what, alarm.when);
        armNextAlarmWakeup();
        createTimelinePin(alarm.what, alarm.when, 'system://images/ALARM_CLOCK', function(err) {
          if (err) { console.log('Timeline pin failed: ' + err); }
          sendToWatch(KEY_RESPONSE, truncateForWatch(displayText));
        });
      } else {
        sendToWatch(KEY_RESPONSE, truncateForWatch(displayText));
      }
    },
    function(errMsg) {
      isLoading = false;
      sendToWatch(KEY_STATUS, errMsg);
    }
  );
}

